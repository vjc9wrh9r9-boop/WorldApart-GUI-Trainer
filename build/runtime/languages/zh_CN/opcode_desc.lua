-- 前缀匹配回退
local OPCODE_DESC_PREFIX = {
  ['near return to calling procedure and pop '] = '近返回并弹出',
  ['far return to calling procedure and pop '] = '远返回并弹出',
}

-- 预建小写查找表（碰撞 key 不入表，需精确匹�）。
local OPCODE_DESC_LOWER = {}
local OPCODE_DESC_LOWER_COLLISIONS = {}
for key, value in pairs(OPCODE_DESC) do
  local lowerKey = key:lower()
  if OPCODE_DESC_LOWER_COLLISIONS[lowerKey] then
    -- 已标记碰撞，跳过
  elseif OPCODE_DESC_LOWER[lowerKey] == nil then
    OPCODE_DESC_LOWER[lowerKey] = value
  elseif OPCODE_DESC_LOWER[lowerKey] ~= value then
    -- 翻译不同，移除并标记冲突
    OPCODE_DESC_LOWER[lowerKey] = nil
    OPCODE_DESC_LOWER_COLLISIONS[lowerKey] = true
  end
end

-- 安装反汇编 opcode 描述翻译包装。
local function install()
  if type(getDefaultDisassembler) ~= 'function' then return end

  local d = getDefaultDisassembler()
  if not d then return end

  local stateKey = '__zhCNOpcodeDescState'
  local state = rawget(_G, stateKey)
  if type(state) ~= 'table' then
    state = {}
    rawset(_G, stateKey, state)
  end
  if state.disassembler == d and state.wrapper == d.OnPostDisassemble then
    return
  end

  local previous = d.OnPostDisassemble

  local descCache = setmetatable({}, { __mode = 'kv' })

  -- 局部化 string builtin，避免热路径中每次查元表。
  local s_match = string.match
  local s_lower = string.lower
  local s_sub = string.sub

  -- 前缀匹配：把表展开为局部数组，避免 pairs() 开销。
  local prefixList = {}
  for prefix, zh_prefix in pairs(OPCODE_DESC_PREFIX) do
    prefixList[#prefixList + 1] = { prefix, zh_prefix, #prefix }
  end

  local wrapper
  -- 翻译 opcode 描述后交回 CE 显示。
  wrapper = function(sender, address, ldd, result, description)
    if previous then
      local newResult, newDescription = previous(sender, address, ldd, result, description)
      if newResult ~= nil then result = newResult end
      if newDescription ~= nil then description = newDescription end
    end

    if not description or description == '' then
      return result, description
    end

    -- 缓存命中
    local cached = descCache[description]
    if cached ~= nil then
      return result, cached
    end

    local desc = s_match(description, '^%s*(.-)%s*$')
    if desc == '' then
      descCache[description] = description
      return result, description
    end

    -- 精确匹配
    local zh = OPCODE_DESC[desc]
    if zh then
      descCache[description] = zh
      return result, zh
    end

    -- 大小写不敏感回退
    local descLower = s_lower(desc)
    zh = OPCODE_DESC_LOWER[descLower]
    if zh then
      descCache[description] = zh
      return result, zh
    end

    -- 前缀匹配
    for i = 1, #prefixList do
      local entry = prefixList[i]
      local prefix = entry[1]
      local plen = entry[3]
      if s_sub(desc, 1, plen) == prefix then
        local translated = entry[2] .. s_sub(desc, plen + 1)
        descCache[description] = translated
        return result, translated
      end
    end

    descCache[description] = description
    return result, description
  end

  d.OnPostDisassemble = wrapper
  state.disassembler = d
  state.wrapper = wrapper
end

pcall(install)
